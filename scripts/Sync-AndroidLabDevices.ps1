# Regenerates the per-device blocks in installer/AndroidLab.iss from installer/devices/*.json.
# Run after adding/removing a device json:
#   powershell -File scripts/Sync-AndroidLabDevices.ps1
# Optional: -IssPath / -DevicesDir to override defaults. -Check only verifies, for CI.
param(
  [string]$IssPath = (Join-Path $PSScriptRoot "..\installer\AndroidLab.iss"),
  [string]$DevicesDir = (Join-Path $PSScriptRoot "..\installer\devices"),
  [switch]$Check
)
$ErrorActionPreference = "Stop"
$IssPath = [IO.Path]::GetFullPath($IssPath)
$DevicesDir = [IO.Path]::GetFullPath($DevicesDir)

$files = Get-ChildItem $DevicesDir -Filter "*.json" | Sort-Object Name
if ($files.Count -eq 0) { throw "no device json found in $DevicesDir" }

$devices = foreach ($f in $files) {
  $d = Get-Content $f.FullName -Raw | ConvertFrom-Json
  $base = [IO.Path]::GetFileNameWithoutExtension($f.Name)
  if (-not $d.id) { $d | Add-Member -NotePropertyName id -NotePropertyValue $base.ToLowerInvariant() }
  if (-not $d.exe) { $d | Add-Member -NotePropertyName exe -NotePropertyValue $base }
  if (-not $d.title) { $d | Add-Member -NotePropertyName title -NotePropertyValue $base }
  if (-not $d.description) { $d | Add-Member -NotePropertyName description -NotePropertyValue $d.title }
  if (-not $d.avd) { throw "$($f.Name): missing 'avd'" }
  if (-not $d.image_package) { throw "$($f.Name): missing 'image_package'" }
  if (-not $d.target) { throw "$($f.Name): missing 'target'" }
  $staging = Join-Path (Join-Path (Split-Path $DevicesDir) "staging") ($d.exe + ".exe")
  if (-not (Test-Path $staging)) { Write-Warning "$($f.Name): missing staging exe $staging (build the launcher first)" }
  $d | Add-Member -NotePropertyName jsonFile -NotePropertyValue $f.Name -Force
  $d
}

$components = foreach ($d in $devices) {
  'Name: "{0}"; Description: "{1}"; Types: full custom; ExtraDiskSpaceRequired: 6442450944' -f $d.id, $d.description
}
$fs = foreach ($d in $devices) {
  'Source: "staging\{0}.exe"; DestDir: "{{app}}"; Components: {1}; Flags: ignoreversion' -f $d.exe, $d.id
  'Source: "devices\{0}"; DestDir: "{{app}}"; Components: {1}; Flags: ignoreversion' -f $d.jsonFile, $d.id
}
$icons = foreach ($d in $devices) {
  'Name: "{{group}}\{0}"; Filename: "{{app}}\{1}.exe"; WorkingDir: "{{app}}"; Components: {2}' -f $d.title, $d.exe, $d.id
  'Name: "{{autodesktop}}\{0}"; Filename: "{{app}}\{1}.exe"; WorkingDir: "{{app}}"; Components: {2}; Tasks: desktopicon' -f $d.title, $d.exe, $d.id
}
$runs = foreach ($d in $devices) {
  'Filename: "powershell"; Parameters: "-ExecutionPolicy Bypass -File ""{{app}}\shared\Fetch-Device.ps1"" -InstallDir ""{{app}}"" -AvdName {0} -ImagePackage ""{1}"" -Target {2} -Template ""{{app}}\templates\avd-config.ini"""; StatusMsg: "Downloading {3} (~3 GB, one time)..."; Components: {4}; Flags: waituntilterminated' -f $d.avd, $d.image_package, $d.target, $d.title, $d.id
}

function Set-SectionBlock($text, $section, $newLines) {
  $begin = '; BEGIN DEVICES (auto-generated by scripts/Sync-AndroidLabDevices.ps1, do not edit by hand)'
  $end = '; END DEVICES'
  $h = $text.IndexOf("[$section]", [StringComparison]::OrdinalIgnoreCase)
  if ($h -lt 0) { throw "section [$section] not found in $IssPath" }
  $b = $text.IndexOf($begin, $h, [StringComparison]::Ordinal)
  if ($b -lt 0) { throw "BEGIN DEVICES marker not found under [$section] in $IssPath" }
  $e = $text.IndexOf($end, $b, [StringComparison]::Ordinal)
  if ($e -lt 0) { throw "END DEVICES marker not found under [$section] in $IssPath" }
  $eEnd = $e + $end.Length
  $block = $begin + "`n" + ($newLines -join "`n") + "`n" + $end
  return $text.Substring(0, $b) + $block + $text.Substring($eEnd)
}

$text = [IO.File]::ReadAllText($IssPath) -replace "`r`n?", "`n"
$text = Set-SectionBlock $text 'Components' $components
# keep the "; per-device launcher + config" comment line inside [Files] above the block: untouched.
$text = Set-SectionBlock $text 'Files' $fs
$text = Set-SectionBlock $text 'Icons' $icons
$text = Set-SectionBlock $text 'Run' $runs

if ($Check) {
  $current = [IO.File]::ReadAllText($IssPath) -replace "`r`n?", "`n"
  if ($current -ne $text) { throw "$IssPath is out of sync with devices/*.json. Run scripts/Sync-AndroidLabDevices.ps1" }
  Write-Host "in sync: $($devices.Count) device(s)."
} else {
  [IO.File]::WriteAllText($IssPath, ($text -replace "`n", "`r`n"), [Text.Encoding]::ASCII)
  Write-Host "synced $($devices.Count) device(s) into $IssPath"
}
